"""Produce a self-contained handover document from the project's current
state — verified memory, open gaps, overview, and open questions."""
from __future__ import annotations

import json
from datetime import datetime

from .db import connect


def _header(name: str, created_at: str) -> str:
    return (
        f"# {name} — Handover document\n\n"
        f"_Generated by KT Intelligence on {datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')}._\n"
        f"_Project created {created_at}._\n\n"
        "This document consolidates verified knowledge, unresolved gaps, and open "
        "questions that an incoming developer should review first.\n"
    )


def build_markdown(project_id: int) -> str:
    with connect() as conn:
        project = conn.execute("SELECT * FROM projects WHERE id = ?", [project_id]).fetchone()
        if not project:
            raise ValueError("project not found")
        sources = conn.execute(
            "SELECT filename, kind, size_bytes, origin FROM sources WHERE project_id = ? AND superseded_by IS NULL ORDER BY kind, filename",
            [project_id],
        ).fetchall()
        memory = conn.execute(
            "SELECT * FROM memory_records WHERE project_id = ? ORDER BY verification_status, updated_at DESC",
            [project_id],
        ).fetchall()
        findings = conn.execute(
            "SELECT * FROM findings WHERE project_id = ? AND status IN ('open','awaiting') ORDER BY CASE severity WHEN 'high' THEN 0 WHEN 'medium' THEN 1 ELSE 2 END, created_at DESC",
            [project_id],
        ).fetchall()

    out = [_header(project["name"], project["created_at"])]

    out.append("\n## Sources\n")
    if not sources:
        out.append("_No sources ingested._\n")
    else:
        out.append("| File | Kind | Origin |\n|---|---|---|\n")
        for s in sources:
            out.append(f"| `{s['filename']}` | {s['kind']} | {s['origin'] or 'upload'} |\n")

    out.append("\n## Verified knowledge\n")
    verified = [m for m in memory if m["verification_status"] == "verified"]
    if not verified:
        out.append("_No verified records yet._\n")
    for m in verified:
        out.append(f"\n### {m['topic']}\n\n{m['content']}\n")
        srcs = json.loads(m["sources_json"] or "[]")
        if srcs:
            out.append("\n**Sources:** " + ", ".join(
                f"`{s.get('filename','?')}" + (f":{s.get('start_line')}-{s.get('end_line')}" if s.get('start_line') else "") + "`"
                for s in srcs
            ) + "\n")

    out.append("\n## Unresolved / pending\n")
    pending = [m for m in memory if m["verification_status"] in ("unverified", "conflicting", "ai_suggested")]
    if not pending:
        out.append("_No pending records._\n")
    for m in pending:
        out.append(f"\n### [{m['verification_status']}] {m['topic']}\n\n{m['content']}\n")

    out.append("\n## Open gaps\n")
    if not findings:
        out.append("_No open findings._\n")
    for f in findings:
        kt = json.loads(f["kt_evidence_json"] or "null")
        code = json.loads(f["code_evidence_json"] or "null") or []
        out.append(f"\n### [{f['severity']}] {f['title']}\n")
        out.append(f"\n**Category:** {f['category']} · **Confidence:** {int((f['confidence'] or 0)*100)}% · **Status:** {f['status']}\n")
        out.append(f"\n{f['explanation']}\n")
        if kt:
            out.append(f"\n**KT claim** — `{kt.get('filename')}:{kt.get('start_line')}-{kt.get('end_line')}`\n\n> {kt.get('excerpt','').strip()}\n")
        if code:
            out.append("\n**Code evidence:**\n")
            for c in code[:3]:
                out.append(f"\n`{c.get('filename')}:{c.get('start_line')}-{c.get('end_line')}`\n\n```\n{(c.get('excerpt') or c.get('text') or '').strip()}\n```\n")
        if f["suggested_question"]:
            out.append(f"\n**Suggested question for the outgoing team:** {f['suggested_question']}\n")

    out.append("\n---\n_End of handover._\n")
    return "".join(out)
